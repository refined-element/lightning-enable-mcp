using System.Diagnostics;
using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

namespace LightningEnable.Mcp.Services;

/// <summary>One heading and the lines up to the next heading of any level.</summary>
/// <param name="Heading">Heading text, or <c>null</c> for the text before a page's first heading.</param>
/// <param name="Level">1-6, or 0 for that leading text.</param>
/// <param name="Start">Index of the heading line in the page's lines (0 for leading text).</param>
/// <param name="End">Exclusive end of this leaf section.</param>
/// <param name="Body">Text between this heading and the next one.</param>
public sealed record DocsSection(string? Heading, int Level, int Start, int End, string Body);

/// <summary>One docs page from <c>llms-full.txt</c>.</summary>
public sealed record DocsPage(
    string Title, string Url, string Path, IReadOnlyList<string> Lines, IReadOnlyList<DocsSection> Sections);

/// <summary>
/// Parser, search and read over Lightning Enable's <c>llms-full.txt</c>: the whole docs site
/// in one plain-text file, generated by <c>docs-site/scripts/generate-llms-full.mjs</c> in the
/// main Lightning Enable repo. That generator emits one block per page:
/// <code>
/// ==============================================================================
/// # &lt;page title&gt;
/// Source: https://docs.lightningenable.com/&lt;route&gt;
/// ==============================================================================
///
/// &lt;page markdown&gt;
/// </code>
/// The parser keys on that four-line header, so a <c>=====</c> line or a <c># heading</c>
/// inside a page body is never mistaken for a page boundary. Inside a page, ATX headings
/// outside code fences split it into sections.
///
/// <para>Deterministic and dependency-free, and identical to the Python port
/// (<c>docs_service.py</c>): same tokens, scores, snippets and truncation point. Both test
/// suites assert on <c>shared/docs/docs-tool-cases.json</c>. Whitespace is matched with
/// explicit character sets rather than <c>\s</c> / <c>Trim()</c>, because the two runtimes
/// disagree on a few control characters.</para>
/// </summary>
public static class DocsCorpus
{
    /// <summary>Most UTF-8 bytes <c>read</c> returns.</summary>
    public const int MaxReadBytes = 12_000;

    /// <summary>Default number of search results.</summary>
    public const int DefaultSearchLimit = 5;

    /// <summary>Largest number of search results.</summary>
    public const int MaxSearchLimit = 20;

    /// <summary>Most headings listed in a read result's <c>sections</c>.</summary>
    public const int MaxListedSections = 100;

    /// <summary>Weight of a query term found in a section's title against one in its body.</summary>
    public const int TitleWeight = 5;

    private const int SnippetLeadWords = 10;
    private const int SnippetWords = 40;

    private static readonly string Divider = new('=', 78);
    private static readonly char[] Blank = { ' ', '\t', '\f', '\v' };
    private static readonly char[] Trim = { ' ', '\t', '\n', '\r', '\f', '\v' };

    private static readonly HashSet<string> Stopwords = new(StringComparer.Ordinal)
    {
        "a", "an", "and", "are", "as", "at", "be", "by", "can", "do", "does", "for",
        "from", "how", "i", "in", "is", "it", "my", "of", "on", "or", "the", "to",
        "what", "when", "where", "with",
    };

    private static readonly Regex Token = new("[a-z0-9]+", RegexOptions.CultureInvariant);
    private static readonly Regex Heading = new(@"^(#{1,6})[ \t]+(.+?)[ \t]*$", RegexOptions.CultureInvariant);
    private static readonly Regex ClosingHashes = new(@"[ \t]+#+$", RegexOptions.CultureInvariant);
    private static readonly Regex Fence = new(@"^[ \t]*(?:```|~~~)", RegexOptions.CultureInvariant);
    private static readonly Regex Whitespace = new(@"[ \t\n\f\v]+", RegexOptions.CultureInvariant);
    private static readonly Regex Origin = new(@"^[A-Za-z][A-Za-z0-9+.-]*://[^/?#]*", RegexOptions.CultureInvariant);

    // ── Parsing ────────────────────────────────────────────────────────────────

    /// <summary>Splits an llms-full.txt corpus into pages and their sections.</summary>
    public static IReadOnlyList<DocsPage> Parse(string text)
    {
        var lines = text.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
        var starts = Enumerable.Range(0, lines.Length).Where(i => IsHeader(lines, i)).ToList();
        var pages = new List<DocsPage>(starts.Count);
        for (var n = 0; n < starts.Count; n++)
        {
            var start = starts[n];
            var end = n + 1 < starts.Count ? starts[n + 1] : lines.Length;
            var title = lines[start + 1][2..].Trim(Trim);
            var url = lines[start + 2]["Source: ".Length..].Trim(Trim);
            var body = TrimBlankLines(lines[(start + 4)..end]);
            var path = PathOf(url);
            pages.Add(new DocsPage(title.Length > 0 ? title : path, url, path, body, SplitSections(body)));
        }

        return pages;
    }

    private static bool IsHeader(string[] lines, int i)
        => i + 3 < lines.Length
           && lines[i] == Divider
           && lines[i + 1].StartsWith("# ", StringComparison.Ordinal)
           && lines[i + 2].StartsWith("Source: ", StringComparison.Ordinal)
           && lines[i + 3] == Divider;

    private static bool IsBlank(string line) => line.Trim(Blank).Length == 0;

    private static string[] TrimBlankLines(IReadOnlyList<string> lines)
    {
        int start = 0, end = lines.Count;
        while (start < end && IsBlank(lines[start]))
        {
            start++;
        }

        while (end > start && IsBlank(lines[end - 1]))
        {
            end--;
        }

        return lines.Skip(start).Take(end - start).ToArray();
    }

    /// <summary>Site-relative path of a docs URL: <c>/nwc-setup/account-setup</c>, or <c>/</c>.</summary>
    public static string PathOf(string url)
    {
        var rest = Origin.Replace(url.Trim(Trim), string.Empty, 1);
        foreach (var mark in new[] { '#', '?' })
        {
            var cut = rest.IndexOf(mark, StringComparison.Ordinal);
            if (cut >= 0)
            {
                rest = rest[..cut];
            }
        }

        if (!rest.StartsWith('/'))
        {
            rest = "/" + rest;
        }

        if (rest.Length > 1)
        {
            rest = rest.TrimEnd('/');
            if (rest.Length == 0)
            {
                rest = "/";
            }
        }

        return rest;
    }

    private static (int Level, string Text)? HeadingOf(string line)
    {
        var match = Heading.Match(line);
        if (!match.Success)
        {
            return null;
        }

        var text = ClosingHashes.Replace(match.Groups[2].Value, string.Empty).Trim(Trim);
        return text.Length == 0 ? null : (match.Groups[1].Value.Length, text);
    }

    private static List<DocsSection> SplitSections(string[] lines)
    {
        var headings = new List<(int Index, int Level, string Text)>();
        var inFence = false;
        for (var i = 0; i < lines.Length; i++)
        {
            if (Fence.IsMatch(lines[i]))
            {
                inFence = !inFence;
                continue;
            }

            if (inFence)
            {
                continue;
            }

            if (HeadingOf(lines[i]) is { } heading)
            {
                headings.Add((i, heading.Level, heading.Text));
            }
        }

        var sections = new List<DocsSection>();
        var first = headings.Count > 0 ? headings[0].Index : lines.Length;
        var intro = TrimBlankLines(lines[..first]);
        if (intro.Length > 0)
        {
            sections.Add(new DocsSection(null, 0, 0, first, string.Join("\n", intro)));
        }

        for (var n = 0; n < headings.Count; n++)
        {
            var (index, level, text) = headings[n];
            var end = n + 1 < headings.Count ? headings[n + 1].Index : lines.Length;
            var body = string.Join("\n", TrimBlankLines(lines[(index + 1)..end]));
            sections.Add(new DocsSection(text, level, index, end, body));
        }

        return sections;
    }

    // ── Text helpers ───────────────────────────────────────────────────────────

    /// <summary>Lower-cased ASCII letter/digit runs.</summary>
    public static List<string> Tokens(string text)
        => Token.Matches(text.ToLowerInvariant()).Select(m => m.Value).ToList();

    /// <summary>Approximation of the Docusaurus heading id: <c>Using Your API Key</c> → <c>using-your-api-key</c>.</summary>
    public static string Anchor(string heading)
    {
        var sb = new StringBuilder();
        foreach (var ch in heading.ToLowerInvariant())
        {
            if (ch is (>= 'a' and <= 'z') or (>= '0' and <= '9') or '-' or '_')
            {
                sb.Append(ch);
            }
            else if (ch == ' ')
            {
                sb.Append('-');
            }
        }

        return sb.ToString();
    }

    /// <summary>
    /// Caps <paramref name="text"/> at <paramref name="maxBytes"/> of UTF-8, never splitting a
    /// character. When a line break lies past the halfway point of the cut, the text is cut
    /// there instead, so the result does not end mid-sentence.
    /// </summary>
    public static (string Text, bool Truncated) TruncateUtf8(string text, int maxBytes)
    {
        if (Encoding.UTF8.GetByteCount(text) <= maxBytes)
        {
            return (text, false);
        }

        var used = 0;
        var length = 0;
        foreach (var rune in text.EnumerateRunes())
        {
            if (used + rune.Utf8SequenceLength > maxBytes)
            {
                break;
            }

            used += rune.Utf8SequenceLength;
            length += rune.Utf16SequenceLength;
        }

        var cut = text[..length];
        var newline = cut.LastIndexOf('\n');
        if (newline >= 0 && Encoding.UTF8.GetByteCount(cut[..newline]) >= maxBytes / 2)
        {
            cut = cut[..newline];
        }

        return (cut.TrimEnd(Trim), true);
    }

    private static List<string> QueryTerms(string query)
    {
        var seen = new List<string>();
        foreach (var token in Tokens(query))
        {
            if (!seen.Contains(token))
            {
                seen.Add(token);
            }
        }

        var meaningful = seen.Where(t => !Stopwords.Contains(t)).ToList();
        return meaningful.Count > 0 ? meaningful : seen;
    }

    private static string Snippet(string body, List<string> terms)
    {
        var words = Whitespace.Split(body).Where(w => w.Length > 0).ToList();
        if (words.Count == 0)
        {
            return string.Empty;
        }

        var hit = words.FindIndex(w => Tokens(w).Any(terms.Contains));
        var start = hit < 0 ? 0 : Math.Max(0, hit - SnippetLeadWords);
        var end = Math.Min(words.Count, start + SnippetWords);
        var text = string.Join(" ", words.Skip(start).Take(end - start));
        if (start > 0)
        {
            text = "..." + text;
        }

        if (end < words.Count)
        {
            text += "...";
        }

        return text;
    }

    private static bool IsPageHeading(DocsPage page, DocsSection section)
        => section.Heading is null
           || (section.Level == 1
               && string.Equals(section.Heading.ToLowerInvariant(), page.Title.ToLowerInvariant(), StringComparison.Ordinal));

    private static string SectionUrl(DocsPage page, DocsSection section)
        => IsPageHeading(page, section) ? page.Url : $"{page.Url}#{Anchor(section.Heading!)}";

    private static JsonArray ListedSections(DocsPage page)
        => new(page.Sections
            .Where(s => s.Heading != null && !IsPageHeading(page, s))
            .Take(MaxListedSections)
            .Select(s => (JsonNode)JsonValue.Create(s.Heading)!)
            .ToArray());

    private static JsonObject Error(string message) => new() { ["success"] = false, ["error"] = message };

    // ── Search and read ───────────────────────────────────────────────────────

    /// <summary>Ranks sections by term frequency, title matches weighted <see cref="TitleWeight"/>.</summary>
    public static JsonObject Search(IReadOnlyList<DocsPage> pages, string? query, int? limit)
    {
        var terms = QueryTerms(query ?? string.Empty);
        if (terms.Count == 0)
        {
            return Error("docs search needs a query containing letters or digits, e.g. query='nwc connection string'.");
        }

        var size = limit is null ? DefaultSearchLimit : Math.Clamp(limit.Value, 1, MaxSearchLimit);

        var scored = new List<(int Matched, int Score, int Page, int Section)>();
        for (var p = 0; p < pages.Count; p++)
        {
            var page = pages[p];
            for (var s = 0; s < page.Sections.Count; s++)
            {
                var section = page.Sections[s];
                var titleTokens = Tokens($"{page.Title} {section.Heading ?? page.Title}");
                var bodyTokens = Tokens(section.Body);
                int matched = 0, score = 0;
                foreach (var term in terms)
                {
                    var inTitle = titleTokens.Count(t => t == term);
                    var inBody = bodyTokens.Count(t => t == term);
                    if (inTitle > 0 || inBody > 0)
                    {
                        matched++;
                    }

                    score += TitleWeight * inTitle + inBody;
                }

                if (matched > 0)
                {
                    scored.Add((matched, score, p, s));
                }
            }
        }

        var results = new JsonArray();
        foreach (var hit in scored
                     .OrderByDescending(r => r.Matched)
                     .ThenByDescending(r => r.Score)
                     .ThenBy(r => r.Page)
                     .ThenBy(r => r.Section)
                     .Take(size))
        {
            var page = pages[hit.Page];
            var section = page.Sections[hit.Section];
            results.Add(new JsonObject
            {
                ["title"] = IsPageHeading(page, section) ? page.Title : $"{page.Title} > {section.Heading}",
                ["path"] = page.Path,
                ["url"] = SectionUrl(page, section),
                ["section"] = section.Heading,
                ["snippet"] = Snippet(section.Body, terms),
            });
        }

        return new JsonObject
        {
            ["success"] = true,
            ["query"] = query,
            ["count"] = results.Count,
            ["results"] = results,
        };
    }

    /// <summary>Normalizes a caller's path; returns the path and the <c>#fragment</c>, if any.</summary>
    public static (string Path, string? Fragment) NormalizePath(string raw)
    {
        var value = raw.Trim(Trim);
        string? fragment = null;
        var hash = value.IndexOf('#', StringComparison.Ordinal);
        if (hash >= 0)
        {
            fragment = Uri.UnescapeDataString(value[(hash + 1)..]).Trim(Trim);
            if (fragment.Length == 0)
            {
                fragment = null;
            }

            value = value[..hash];
        }

        return (PathOf(value), fragment);
    }

    private static DocsSection? FindSection(DocsPage page, string wanted)
    {
        var target = wanted.Trim(Trim).TrimStart('#').Trim(Trim).ToLowerInvariant();
        if (target.Length == 0)
        {
            return null;
        }

        var named = page.Sections.Where(s => s.Heading != null).ToList();
        var exact = named.FirstOrDefault(s => s.Heading!.ToLowerInvariant() == target);
        if (exact != null)
        {
            return exact;
        }

        var targetAnchor = Anchor(target);
        var byAnchor = targetAnchor.Length > 0
            ? named.FirstOrDefault(s => Anchor(s.Heading!) == targetAnchor)
            : null;
        return byAnchor ?? named.FirstOrDefault(
            s => s.Heading!.ToLowerInvariant().Contains(target, StringComparison.Ordinal));
    }

    /// <summary>Returns one page, or one section of it with its subsections, as text.</summary>
    public static JsonObject Read(IReadOnlyList<DocsPage> pages, string? path, string? section, int maxBytes = MaxReadBytes)
    {
        if (string.IsNullOrWhiteSpace(path))
        {
            return Error("docs read needs a path, e.g. path='/nwc-setup/account-setup'. Use action='search' to find one.");
        }

        var (wantedPath, fragment) = NormalizePath(path);
        var wantedSection = !string.IsNullOrWhiteSpace(section) ? section : fragment;

        var page = pages.FirstOrDefault(p => p.Path.ToLowerInvariant() == wantedPath.ToLowerInvariant());
        if (page is null)
        {
            var last = wantedPath.Split('/').LastOrDefault(s => s.Length > 0)?.ToLowerInvariant() ?? string.Empty;
            var suggestions = last.Length == 0
                ? new List<string>()
                : pages.Where(p => p.Path.ToLowerInvariant().Contains(last, StringComparison.Ordinal))
                    .Select(p => p.Path).Take(5).ToList();
            var notFound = Error($"No docs page at '{wantedPath}'. Use action='search' to find the right path.");
            if (suggestions.Count > 0)
            {
                notFound["suggestions"] = new JsonArray(suggestions.Select(s => (JsonNode)JsonValue.Create(s)!).ToArray());
            }

            return notFound;
        }

        string text;
        string? heading;
        string url;
        if (wantedSection != null)
        {
            var found = FindSection(page, wantedSection);
            if (found is null)
            {
                var missing = Error($"No section '{wantedSection.Trim(Trim)}' on {page.Path}.");
                missing["path"] = page.Path;
                missing["sections"] = ListedSections(page);
                return missing;
            }

            var end = page.Lines.Count;
            if (found.Level > 0)
            {
                var next = page.Sections.FirstOrDefault(
                    o => o.Start > found.Start && o.Level > 0 && o.Level <= found.Level);
                if (next != null)
                {
                    end = next.Start;
                }
            }

            text = string.Join("\n", TrimBlankLines(page.Lines.Skip(found.Start).Take(end - found.Start).ToArray()));
            heading = found.Heading;
            url = SectionUrl(page, found);
        }
        else
        {
            text = string.Join("\n", page.Lines);
            heading = null;
            url = page.Url;
        }

        var (capped, truncated) = TruncateUtf8(text, maxBytes);
        var result = new JsonObject
        {
            ["success"] = true,
            ["title"] = page.Title,
            ["path"] = page.Path,
            ["url"] = url,
            ["section"] = heading,
            ["text"] = capped,
            ["truncated"] = truncated,
            ["sections"] = ListedSections(page),
        };
        if (truncated)
        {
            result["hint"] = $"Text was cut at {maxBytes} bytes. Read one of 'sections' for the rest, or open {url}.";
        }

        return result;
    }
}

/// <summary>Search and read the Lightning Enable docs. Backs the <c>docs</c> tool.</summary>
public interface IDocsService
{
    /// <summary>Where the corpus is loaded from.</summary>
    string SourceUrl { get; }

    /// <summary>Ranked sections matching <paramref name="query"/>.</summary>
    Task<JsonObject> SearchAsync(string? query, int? limit, CancellationToken cancellationToken = default);

    /// <summary>A page, or one section of it, as text.</summary>
    Task<JsonObject> ReadAsync(string? path, string? section, CancellationToken cancellationToken = default);
}

/// <summary>
/// Loads <c>llms-full.txt</c>, caches it in memory for an hour, and serves search/read.
/// On a failed refresh the stale copy is served (flagged <c>stale</c>) and the next attempt
/// waits <see cref="RetryAfterFailureSeconds"/>; with nothing cached, the error names the
/// URL. No API key and no wallet are needed. Mirrors Python's <c>docs_service.DocsService</c>.
/// </summary>
public sealed class DocsService : IDocsService
{
    /// <summary>The published docs corpus.</summary>
    public const string DefaultSourceUrl = "https://docs.lightningenable.com/llms-full.txt";

    /// <summary>Overrides the source: an https:// URL, http:// on localhost, or file://.</summary>
    public const string SourceEnvironmentVariable = "LIGHTNING_ENABLE_DOCS_URL";

    /// <summary>Named <see cref="IHttpClientFactory"/> client used for the fetch.</summary>
    public const string HttpClientName = "Docs";

    /// <summary>How long a fetched corpus is served before the next call refetches it.</summary>
    public const double CacheTtlSeconds = 3600;

    /// <summary>After a failed refresh, how long the stale copy is served before retrying.</summary>
    public const double RetryAfterFailureSeconds = 60;

    /// <summary>Largest source accepted (the live file is about 1 MB).</summary>
    public const int MaxSourceBytes = 10 * 1024 * 1024;

    private static readonly TimeSpan FetchTimeout = TimeSpan.FromSeconds(15);

    private static readonly HashSet<string> LoopbackHosts = new(StringComparer.OrdinalIgnoreCase)
    {
        "localhost", "127.0.0.1", "::1", "[::1]",
    };

    private static readonly Lazy<HttpClient> FallbackClient = new(() => CreateHttpClient(new SocketsHttpHandler
    {
        AllowAutoRedirect = true,
        MaxAutomaticRedirections = 5,
    }));

    private readonly Func<string, CancellationToken, Task<string>> _fetch;
    private readonly Func<double> _clock;
    private readonly Func<HttpClient>? _httpClient;
    private readonly SemaphoreSlim _lock = new(1, 1);
    private IReadOnlyList<DocsPage>? _pages;
    private double _loadedAt;
    private double _retryAt;

    /// <summary>Creates the service.</summary>
    /// <param name="sourceUrl">Source; <c>null</c> reads <see cref="SourceEnvironmentVariable"/>, then the default.</param>
    /// <param name="fetch">Replaces the network/file fetch (tests).</param>
    /// <param name="clockSeconds">Monotonic clock in seconds (tests).</param>
    /// <param name="httpClient">Supplies the HTTP client (Program passes the named factory client).</param>
    public DocsService(
        string? sourceUrl = null,
        Func<string, CancellationToken, Task<string>>? fetch = null,
        Func<double>? clockSeconds = null,
        Func<HttpClient>? httpClient = null)
    {
        SourceUrl = ResolveSourceUrl(sourceUrl ?? Environment.GetEnvironmentVariable(SourceEnvironmentVariable));
        _fetch = fetch ?? DefaultFetchAsync;
        _clock = clockSeconds ?? (() => Stopwatch.GetTimestamp() / (double)Stopwatch.Frequency);
        _httpClient = httpClient;
    }

    /// <inheritdoc />
    public string SourceUrl { get; }

    /// <summary>The configured source, or the default when blank.</summary>
    public static string ResolveSourceUrl(string? configured)
        => string.IsNullOrWhiteSpace(configured) ? DefaultSourceUrl : configured.Trim();

    /// <summary>Builds an HTTP client with the docs fetch's timeout and headers.</summary>
    public static HttpClient CreateHttpClient(HttpMessageHandler handler) => ConfigureHttpClient(new HttpClient(handler));

    /// <summary>Applies the docs fetch's timeout and headers.</summary>
    public static HttpClient ConfigureHttpClient(HttpClient client)
    {
        client.Timeout = FetchTimeout;
        client.DefaultRequestHeaders.TryAddWithoutValidation("User-Agent", UserAgent.Value);
        client.DefaultRequestHeaders.TryAddWithoutValidation("Accept", "text/plain");
        return client;
    }

    /// <summary>An error message when <paramref name="url"/> is not an allowed source, else null.</summary>
    public static string? ValidateSourceUrl(string url)
    {
        if (Uri.TryCreate(url, UriKind.Absolute, out var uri))
        {
            if (uri.Scheme == Uri.UriSchemeHttps && uri.Host.Length > 0)
            {
                return null;
            }

            if (uri.Scheme == Uri.UriSchemeFile)
            {
                return null;
            }

            if (uri.Scheme == Uri.UriSchemeHttp && LoopbackHosts.Contains(uri.Host))
            {
                return null;
            }
        }

        return $"{SourceEnvironmentVariable} must be an https:// URL (http:// only for localhost, or file://); got '{url}'.";
    }

    private async Task<string> DefaultFetchAsync(string url, CancellationToken cancellationToken)
    {
        var uri = new Uri(url);
        if (uri.IsFile)
        {
            var info = new FileInfo(uri.LocalPath);
            if (!info.Exists)
            {
                throw new FileNotFoundException($"cannot read {uri.LocalPath}: file not found");
            }

            if (info.Length > MaxSourceBytes)
            {
                throw new InvalidDataException($"file is larger than {MaxSourceBytes} bytes");
            }

            return await File.ReadAllTextAsync(uri.LocalPath, Encoding.UTF8, cancellationToken);
        }

        var client = _httpClient?.Invoke() ?? FallbackClient.Value;
        using var response = await client.GetAsync(uri, HttpCompletionOption.ResponseHeadersRead, cancellationToken);
        if (!response.IsSuccessStatusCode)
        {
            throw new HttpRequestException($"HTTP {(int)response.StatusCode}");
        }

        await using var stream = await response.Content.ReadAsStreamAsync(cancellationToken);
        using var buffer = new MemoryStream();
        var chunk = new byte[81920];
        int read;
        while ((read = await stream.ReadAsync(chunk, cancellationToken)) > 0)
        {
            if (buffer.Length + read > MaxSourceBytes)
            {
                throw new InvalidDataException($"response is larger than {MaxSourceBytes} bytes");
            }

            buffer.Write(chunk, 0, read);
        }

        return Encoding.UTF8.GetString(buffer.GetBuffer(), 0, (int)buffer.Length);
    }

    private async Task<(IReadOnlyList<DocsPage>? Pages, JsonObject Extra)> CorpusAsync(CancellationToken cancellationToken)
    {
        if (ValidateSourceUrl(SourceUrl) is { } invalid)
        {
            return (null, new JsonObject { ["success"] = false, ["error"] = invalid });
        }

        var now = _clock();
        if (_pages != null && now - _loadedAt < CacheTtlSeconds)
        {
            return (_pages, new JsonObject());
        }

        await _lock.WaitAsync(cancellationToken);
        try
        {
            now = _clock();
            if (_pages != null && now - _loadedAt < CacheTtlSeconds)
            {
                return (_pages, new JsonObject());
            }

            if (_pages != null && now < _retryAt)
            {
                return (_pages, StaleFields("the last refresh failed"));
            }

            IReadOnlyList<DocsPage> pages;
            try
            {
                var text = await _fetch(SourceUrl, cancellationToken);
                pages = DocsCorpus.Parse(text);
                if (pages.Count == 0)
                {
                    throw new InvalidDataException("no pages found (is this an llms-full.txt file?)");
                }
            }
            catch (Exception ex) when (ex is not OperationCanceledException || !cancellationToken.IsCancellationRequested)
            {
                var reason = string.IsNullOrWhiteSpace(ex.Message) ? ex.GetType().Name : ex.Message;
                if (_pages != null)
                {
                    _retryAt = now + RetryAfterFailureSeconds;
                    return (_pages, StaleFields(reason));
                }

                return (null, new JsonObject
                {
                    ["success"] = false,
                    ["error"] = $"Could not load the Lightning Enable docs from {SourceUrl}: {reason}. "
                        + $"Check network access, or set {SourceEnvironmentVariable} to a reachable copy of llms-full.txt.",
                });
            }

            _pages = pages;
            _loadedAt = now;
            _retryAt = 0;
            return (pages, new JsonObject());
        }
        finally
        {
            _lock.Release();
        }
    }

    private JsonObject StaleFields(string reason) => new()
    {
        ["stale"] = true,
        ["warning"] = $"Serving a cached copy: refreshing {SourceUrl} failed ({reason}).",
    };

    private JsonObject Finish(JsonObject result, JsonObject extra)
    {
        result["source"] = SourceUrl;
        foreach (var (key, value) in extra.ToList())
        {
            extra.Remove(key);
            result[key] = value;
        }

        return result;
    }

    /// <inheritdoc />
    public async Task<JsonObject> SearchAsync(string? query, int? limit, CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(query))
        {
            return new JsonObject
            {
                ["success"] = false,
                ["error"] = "docs search needs a query, e.g. query='nwc connection string'.",
            };
        }

        var (pages, extra) = await CorpusAsync(cancellationToken);
        return pages is null ? extra : Finish(DocsCorpus.Search(pages, query, limit), extra);
    }

    /// <inheritdoc />
    public async Task<JsonObject> ReadAsync(string? path, string? section, CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(path))
        {
            return DocsCorpus.Read(Array.Empty<DocsPage>(), path, null);
        }

        var (pages, extra) = await CorpusAsync(cancellationToken);
        return pages is null ? extra : Finish(DocsCorpus.Read(pages, path, section), extra);
    }
