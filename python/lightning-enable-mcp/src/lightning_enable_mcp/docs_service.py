"""Lightning Enable documentation, readable by an agent without web access.

Backs the ``docs`` tool. The source is ``llms-full.txt``, the whole docs site in one
plain-text file, generated by ``docs-site/scripts/generate-llms-full.mjs`` in the main
Lightning Enable repo. That generator emits one block per page::

    ==============================================================================
    # <page title>
    Source: https://docs.lightningenable.com/<route>
    ==============================================================================

    <page markdown>

The parser keys on that four-line header (divider, ``# title``, ``Source:``, divider),
so a ``=====`` line or a ``# heading`` inside a page body is never mistaken for a page
boundary. Inside a page, ATX headings (``#`` to ``######``) outside code fences split
it into sections.

Everything here is deterministic and dependency-free, and mirrors the .NET port
(``Services/DocsService.cs``) exactly: same tokens, same scores, same snippets, same
truncation point. ``shared/docs/`` at the repo root holds a sample file and the
expected results both test suites assert on.
"""

from __future__ import annotations

import asyncio
import os
import re
import time
from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import unquote, urlparse
from urllib.request import url2pathname

from ._version import USER_AGENT_MCP

try:
    import httpx
except ImportError:  # pragma: no cover - httpx is a hard dependency
    httpx = None  # type: ignore

#: Default source: the published docs corpus.
DEFAULT_DOCS_URL = "https://docs.lightningenable.com/llms-full.txt"

#: Environment variable that overrides the source (an https:// URL, http:// on
#: localhost, or file://). Tests point it at ``shared/docs/llms-full.sample.txt``.
DOCS_URL_ENV_VAR = "LIGHTNING_ENABLE_DOCS_URL"

#: How long a fetched corpus is served before the next call refetches it.
CACHE_TTL_SECONDS = 3600.0

#: After a failed refresh, how long the stale copy is served before trying again,
#: so a docs outage does not turn every call into a 15-second timeout.
RETRY_AFTER_FAILURE_SECONDS = 60.0

#: Most bytes ``read`` returns. Cut on a line boundary when one is near.
MAX_READ_BYTES = 12_000

#: Largest source accepted (the live file is about 1 MB).
MAX_SOURCE_BYTES = 10 * 1024 * 1024

DEFAULT_SEARCH_LIMIT = 5
MAX_SEARCH_LIMIT = 20

#: Most headings listed in a ``read`` result's ``sections``.
MAX_LISTED_SECTIONS = 100

#: Weight of a query term found in a section's title against one found in its body.
TITLE_WEIGHT = 5

FETCH_TIMEOUT_SECONDS = 15.0

#: Words of context kept before the first match in a snippet, and the snippet length.
SNIPPET_LEAD_WORDS = 10
SNIPPET_WORDS = 40

DIVIDER = "=" * 78

_STOPWORDS = frozenset(
    {
        "a",
        "an",
        "and",
        "are",
        "as",
        "at",
        "be",
        "by",
        "can",
        "do",
        "does",
        "for",
        "from",
        "how",
        "i",
        "in",
        "is",
        "it",
        "my",
        "of",
        "on",
        "or",
        "the",
        "to",
        "what",
        "when",
        "where",
        "with",
    }
)

_TOKEN = re.compile(r"[a-z0-9]+")
_HEADING = re.compile(r"^(#{1,6})[ \t]+(.+?)[ \t]*$")
_CLOSING_HASHES = re.compile(r"[ \t]+#+$")
_FENCE = re.compile(r"^[ \t]*(?:```|~~~)")
# Explicit character classes, not \s: Python and .NET disagree on a few control
# characters, and the two ports must cut snippets and trim lines identically.
_WHITESPACE = re.compile(r"[ \t\n\f\v]+")
_BLANK = " \t\f\v"
_TRIM = _BLANK + "\n\r"
_ORIGIN = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*://[^/?#]*")
_LOOPBACK_HOSTS = frozenset({"localhost", "127.0.0.1", "::1"})


# ── Model ─────────────────────────────────────────────────────────────────────


@dataclass
class DocsSection:
    """One heading and the lines up to the next heading of any level."""

    heading: str | None  # None for the text before a page's first heading
    level: int  # 0 for that leading text
    start: int  # index of the heading line in the page's lines (or 0)
    end: int  # exclusive end of this leaf section
    body: str  # text between this heading and the next one


@dataclass
class DocsPage:
    title: str
    url: str
    path: str
    lines: list[str]
    sections: list[DocsSection] = field(default_factory=list)

    @property
    def body(self) -> str:
        return "\n".join(self.lines)


# ── Parsing ───────────────────────────────────────────────────────────────────


def _is_header(lines: list[str], i: int) -> bool:
    return (
        i + 3 < len(lines)
        and lines[i] == DIVIDER
        and lines[i + 1].startswith("# ")
        and lines[i + 2].startswith("Source: ")
        and lines[i + 3] == DIVIDER
    )


def _trim_blank_lines(lines: list[str]) -> list[str]:
    start, end = 0, len(lines)
    while start < end and not lines[start].strip(_BLANK):
        start += 1
    while end > start and not lines[end - 1].strip(_BLANK):
        end -= 1
    return lines[start:end]


def path_of(url: str) -> str:
    """Site-relative path of a docs URL: ``/nwc-setup/account-setup``, or ``/``."""
    rest = _ORIGIN.sub("", url.strip(_TRIM), count=1)
    for mark in ("#", "?"):
        cut = rest.find(mark)
        if cut >= 0:
            rest = rest[:cut]
    if not rest.startswith("/"):
        rest = "/" + rest
    if len(rest) > 1:
        rest = rest.rstrip("/") or "/"
    return rest


def _heading_of(line: str) -> tuple[int, str] | None:
    match = _HEADING.match(line)
    if not match:
        return None
    text = _CLOSING_HASHES.sub("", match.group(2)).strip(_TRIM)
    if not text:
        return None
    return len(match.group(1)), text


def _split_sections(lines: list[str]) -> list[DocsSection]:
    headings: list[tuple[int, int, str]] = []  # (line index, level, text)
    in_fence = False
    for i, line in enumerate(lines):
        if _FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        heading = _heading_of(line)
        if heading:
            headings.append((i, heading[0], heading[1]))

    sections: list[DocsSection] = []
    first = headings[0][0] if headings else len(lines)
    intro = _trim_blank_lines(lines[:first])
    if intro:
        sections.append(DocsSection(None, 0, 0, first, "\n".join(intro)))
    for n, (index, level, text) in enumerate(headings):
        end = headings[n + 1][0] if n + 1 < len(headings) else len(lines)
        body = "\n".join(_trim_blank_lines(lines[index + 1 : end]))
        sections.append(DocsSection(text, level, index, end, body))
    return sections


def parse(text: str) -> list[DocsPage]:
    """Split an llms-full.txt corpus into pages and their sections."""
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    starts = [i for i in range(len(lines)) if _is_header(lines, i)]
    pages: list[DocsPage] = []
    for n, start in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(lines)
        title = lines[start + 1][2:].strip(_TRIM)
        url = lines[start + 2][len("Source: ") :].strip(_TRIM)
        body_lines = _trim_blank_lines(lines[start + 4 : end])
        page = DocsPage(title=title or path_of(url), url=url, path=path_of(url), lines=body_lines)
        page.sections = _split_sections(body_lines)
        pages.append(page)
    return pages


# ── Text helpers (kept identical to the .NET port) ────────────────────────────


def tokens(text: str) -> list[str]:
    return _TOKEN.findall(text.lower())


def anchor(heading: str) -> str:
    """Approximation of the Docusaurus heading id: ``Using Your API Key`` → ``using-your-api-key``."""
    out = []
    for ch in heading.lower():
        if ("a" <= ch <= "z") or ("0" <= ch <= "9") or ch in "-_":
            out.append(ch)
        elif ch == " ":
            out.append("-")
    return "".join(out)


def _utf8_len(text: str) -> int:
    return len(text.encode("utf-8"))


def truncate_utf8(text: str, max_bytes: int) -> tuple[str, bool]:
    """Cap ``text`` at ``max_bytes`` of UTF-8, never splitting a character.

    When the cut lands past the halfway point of a line break, the text is cut at
    that line break instead, so the result does not end mid-sentence.
    """
    encoded = text.encode("utf-8")
    if len(encoded) <= max_bytes:
        return text, False
    cut = encoded[:max_bytes].decode("utf-8", errors="ignore")
    newline = cut.rfind("\n")
    if newline >= 0 and _utf8_len(cut[:newline]) >= max_bytes // 2:
        cut = cut[:newline]
    return cut.rstrip(_TRIM), True


def _query_terms(query: str) -> list[str]:
    seen: list[str] = []
    for token in tokens(query):
        if token not in seen:
            seen.append(token)
    meaningful = [t for t in seen if t not in _STOPWORDS]
    return meaningful or seen


def _snippet(body: str, terms: list[str]) -> str:
    words = [w for w in _WHITESPACE.split(body) if w]
    if not words:
        return ""
    wanted = set(terms)
    hit = next((k for k, w in enumerate(words) if wanted.intersection(tokens(w))), None)
    start = 0 if hit is None else max(0, hit - SNIPPET_LEAD_WORDS)
    end = min(len(words), start + SNIPPET_WORDS)
    text = " ".join(words[start:end])
    if start > 0:
        text = "..." + text
    if end < len(words):
        text = text + "..."
    return text


def _is_page_heading(page: DocsPage, section: DocsSection) -> bool:
    return section.heading is None or (
        section.level == 1 and section.heading.lower() == page.title.lower()
    )


def _section_url(page: DocsPage, section: DocsSection) -> str:
    if _is_page_heading(page, section):
        return page.url
    assert section.heading is not None
    return f"{page.url}#{anchor(section.heading)}"


# ── Search and read over a parsed corpus ──────────────────────────────────────


def search(pages: list[DocsPage], query: str, limit: int | None = None) -> dict[str, Any]:
    """Rank sections by term frequency (title matches weigh ``TITLE_WEIGHT``)."""
    terms = _query_terms(query or "")
    if not terms:
        return {
            "success": False,
            "error": "docs search needs a query containing letters or digits, "
            "e.g. query='nwc connection string'.",
        }
    size = DEFAULT_SEARCH_LIMIT if limit is None else max(1, min(MAX_SEARCH_LIMIT, int(limit)))

    scored: list[tuple[int, int, int, int, DocsPage, DocsSection]] = []
    for p_index, page in enumerate(pages):
        for s_index, section in enumerate(page.sections):
            heading = section.heading or page.title
            title_tokens = tokens(f"{page.title} {heading}")
            body_tokens = tokens(section.body)
            matched = 0
            score = 0
            for term in terms:
                in_title = title_tokens.count(term)
                in_body = body_tokens.count(term)
                if in_title or in_body:
                    matched += 1
                score += TITLE_WEIGHT * in_title + in_body
            if matched:
                scored.append((matched, score, p_index, s_index, page, section))

    scored.sort(key=lambda r: (-r[0], -r[1], r[2], r[3]))
    results = []
    for _, _, _, _, page, section in scored[:size]:
        title = page.title
        if not _is_page_heading(page, section):
            title = f"{page.title} > {section.heading}"
        results.append(
            {
                "title": title,
                "path": page.path,
                "url": _section_url(page, section),
                "section": section.heading,
                "snippet": _snippet(section.body, terms),
            }
        )
    return {"success": True, "query": query, "count": len(results), "results": results}


def normalize_path(raw: str) -> tuple[str, str | None]:
    """Normalize a caller's path; returns (path, fragment-or-None)."""
    value = raw.strip(_TRIM)
    fragment = None
    hash_at = value.find("#")
    if hash_at >= 0:
        fragment = unquote(value[hash_at + 1 :]).strip(_TRIM) or None
        value = value[:hash_at]
    return path_of(value), fragment


def _find_section(page: DocsPage, wanted: str) -> DocsSection | None:
    target = wanted.strip(_TRIM).lstrip("#").strip(_TRIM).lower()
    if not target:
        return None
    named = [s for s in page.sections if s.heading is not None]
    for section in named:
        if section.heading.lower() == target:  # type: ignore[union-attr]
            return section
    target_anchor = anchor(target)
    for section in named:
        if target_anchor and anchor(section.heading) == target_anchor:  # type: ignore[arg-type]
            return section
    for section in named:
        if target in section.heading.lower():  # type: ignore[union-attr]
            return section
    return None


def _listed_sections(page: DocsPage) -> list[str]:
    return [
        s.heading
        for s in page.sections
        if s.heading is not None and not _is_page_heading(page, s)
    ][:MAX_LISTED_SECTIONS]


def read(
    pages: list[DocsPage],
    path: str,
    section: str | None = None,
    max_bytes: int = MAX_READ_BYTES,
) -> dict[str, Any]:
    """Return one page, or one section of it (with its subsections), as text."""
    if not path or not path.strip():
        return {
            "success": False,
            "error": "docs read needs a path, e.g. path='/nwc-setup/account-setup'. "
            "Use action='search' to find one.",
        }
    wanted_path, fragment = normalize_path(path)
    wanted_section = section if section and section.strip() else fragment

    page = next((p for p in pages if p.path.lower() == wanted_path.lower()), None)
    if page is None:
        last = next((seg for seg in reversed(wanted_path.split("/")) if seg), "").lower()
        suggestions = [p.path for p in pages if last and last in p.path.lower()][:5]
        result: dict[str, Any] = {
            "success": False,
            "error": f"No docs page at '{wanted_path}'. Use action='search' to find the right path.",
        }
        if suggestions:
            result["suggestions"] = suggestions
        return result

    if wanted_section:
        found = _find_section(page, wanted_section)
        if found is None:
            return {
                "success": False,
                "error": f"No section '{wanted_section.strip(_TRIM)}' on {page.path}.",
                "path": page.path,
                "sections": _listed_sections(page),
            }
        end = len(page.lines)
        if found.level > 0:
            for other in page.sections:
                if other.start > found.start and 0 < other.level <= found.level:
                    end = other.start
                    break
        text = "\n".join(_trim_blank_lines(page.lines[found.start : end]))
        heading = found.heading
        url = _section_url(page, found)
    else:
        text = page.body
        heading = None
        url = page.url

    capped, truncated = truncate_utf8(text, max_bytes)
    result = {
        "success": True,
        "title": page.title,
        "path": page.path,
        "url": url,
        "section": heading,
        "text": capped,
        "truncated": truncated,
        "sections": _listed_sections(page),
    }
    if truncated:
        result["hint"] = (
            f"Text was cut at {max_bytes} bytes. Read one of 'sections' for the rest, "
            f"or open {url}."
        )
    return result


# ── Source + cache ────────────────────────────────────────────────────────────


class DocsSourceError(Exception):
    """The docs source could not be fetched or did not look like llms-full.txt."""


def validate_source_url(url: str) -> str | None:
    """Return an error message when ``url`` is not an allowed docs source."""
    parsed = urlparse(url)
    scheme = parsed.scheme.lower()
    if scheme == "https" and parsed.hostname:
        return None
    if scheme == "file":
        return None
    if scheme == "http" and (parsed.hostname or "").lower() in _LOOPBACK_HOSTS:
        return None
    return (
        f"{DOCS_URL_ENV_VAR} must be an https:// URL (http:// only for localhost, "
        f"or file://); got '{url}'."
    )


def _file_url_to_path(url: str) -> Path:
    parsed = urlparse(url)
    raw = unquote(parsed.path)
    if parsed.netloc and parsed.netloc.lower() != "localhost":
        raw = f"//{parsed.netloc}{raw}"
    return Path(url2pathname(raw))


async def default_fetch(url: str) -> str:
    """Fetch the corpus: HTTPS (or loopback HTTP) via httpx, or a file:// path."""
    if urlparse(url).scheme.lower() == "file":
        path = _file_url_to_path(url)
        try:
            data = await asyncio.to_thread(path.read_bytes)
        except OSError as exc:
            raise DocsSourceError(f"cannot read {path}: {exc.strerror or exc}") from exc
        if len(data) > MAX_SOURCE_BYTES:
            raise DocsSourceError(f"file is larger than {MAX_SOURCE_BYTES} bytes")
        return data.decode("utf-8", errors="replace")

    if httpx is None:  # pragma: no cover
        raise DocsSourceError("httpx is not installed")
    try:
        async with httpx.AsyncClient(
            timeout=FETCH_TIMEOUT_SECONDS,
            follow_redirects=True,
            max_redirects=5,
            headers={"User-Agent": USER_AGENT_MCP, "Accept": "text/plain"},
        ) as client:
            async with client.stream("GET", url) as response:
                if response.status_code < 200 or response.status_code >= 300:
                    raise DocsSourceError(f"HTTP {response.status_code}")
                chunks: list[bytes] = []
                size = 0
                async for chunk in response.aiter_bytes():
                    size += len(chunk)
                    if size > MAX_SOURCE_BYTES:
                        raise DocsSourceError(f"response is larger than {MAX_SOURCE_BYTES} bytes")
                    chunks.append(chunk)
    except httpx.HTTPError as exc:
        raise DocsSourceError(type(exc).__name__ + (f": {exc}" if str(exc) else "")) from exc
    return b"".join(chunks).decode("utf-8", errors="replace")


class DocsService:
    """Loads the docs corpus, caches it for an hour, and serves search/read."""

    def __init__(
        self,
        source_url: str | None = None,
        fetch: Callable[[str], Awaitable[str]] | None = None,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        configured = source_url if source_url is not None else os.getenv(DOCS_URL_ENV_VAR)
        self.source_url = (configured or "").strip() or DEFAULT_DOCS_URL
        self._fetch = fetch or default_fetch
        self._clock = clock
        self._pages: list[DocsPage] | None = None
        self._loaded_at = 0.0
        self._retry_at = 0.0
        self._lock = asyncio.Lock()

    async def _corpus(self) -> tuple[list[DocsPage] | None, dict[str, Any]]:
        """Return (pages, extra fields). Pages is None only when nothing is available."""
        invalid = validate_source_url(self.source_url)
        if invalid:
            return None, {"success": False, "error": invalid}

        now = self._clock()
        if self._pages is not None and now - self._loaded_at < CACHE_TTL_SECONDS:
            return self._pages, {}

        async with self._lock:
            now = self._clock()
            if self._pages is not None and now - self._loaded_at < CACHE_TTL_SECONDS:
                return self._pages, {}
            if self._pages is not None and now < self._retry_at:
                return self._pages, self._stale_fields("the last refresh failed")

            try:
                text = await self._fetch(self.source_url)
                pages = parse(text)
                if not pages:
                    raise DocsSourceError("no pages found (is this an llms-full.txt file?)")
            except Exception as exc:  # noqa: BLE001 - every failure becomes a clear message
                reason = str(exc) or type(exc).__name__
                if self._pages is not None:
                    self._retry_at = now + RETRY_AFTER_FAILURE_SECONDS
                    return self._pages, self._stale_fields(reason)
                return None, {
                    "success": False,
                    "error": (
                        f"Could not load the Lightning Enable docs from {self.source_url}: "
                        f"{reason}. Check network access, or set {DOCS_URL_ENV_VAR} to a "
                        "reachable copy of llms-full.txt."
                    ),
                }

            self._pages = pages
            self._loaded_at = now
            self._retry_at = 0.0
            return pages, {}

    def _stale_fields(self, reason: str) -> dict[str, Any]:
        return {
            "stale": True,
            "warning": (f"Serving a cached copy: refreshing {self.source_url} failed ({reason})."),
        }

    async def search(self, query: str | None, limit: int | None = None) -> dict[str, Any]:
        if not query or not query.strip():
            return {
                "success": False,
                "error": "docs search needs a query, e.g. query='nwc connection string'.",
            }
        pages, extra = await self._corpus()
        if pages is None:
            return extra
        result = search(pages, query, limit)
        result["source"] = self.source_url
        return {**result, **extra}

    async def read(self, path: str | None, section: str | None = None) -> dict[str, Any]:
        if not path or not path.strip():
            return read([], "", None)
        pages, extra = await self._corpus()
        if pages is None:
            return extra
        result = read(pages, path, section)
        result["source"] = self.source_url
        return {**result, **extra}
